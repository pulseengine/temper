import { reviewPullRequest, isReviewEnabled, _reviewTimestamps, _resetReviews } from '../../src/ai-review.js';
import { _setConfigForTesting } from '../../src/config.js';
import { runRivetOracle } from '../../src/rivet-oracle.js';

const ORACLE = { enabled: true, binary_path: '/opt/rivet/rivet', timeout_ms: 60000 };

function octokitFor() {
  const posted = [];
  const request = jest.fn((route, params) => {
    if (route === 'GET /repos/{owner}/{repo}/pulls/{pull_number}') {
      if (params.mediaType?.format === 'diff') {
        return Promise.resolve({ data: 'diff --git a/x.rs b/x.rs\n+++ b/x.rs\n@@ -1 +1 @@\n+x\n' });
      }
      return Promise.resolve({
        data: {
          number: 7, title: 't', body: '', user: { login: 'dev' },
          base: { ref: 'main', sha: 'base000', repo: { full_name: 'org/r' } },
          head: { ref: 'f', sha: 'head111', repo: { full_name: 'org/r' } }
        }
      });
    }
    if (route === 'GET /repos/{owner}/{repo}/pulls/{pull_number}/files') {
      return Promise.resolve({ data: [{ filename: 'x.rs', additions: 1, deletions: 1 }] });
    }
    if (route === 'POST /repos/{owner}/{repo}/issues/{issue_number}/comments') {
      posted.push(params.body);
      return Promise.resolve({ status: 201, data: {} });
    }
    return Promise.resolve({ status: 200, data: [] });
  });
  return { request, posted };
}

const finding = {
  source: 'oracle:rivet-validate', severity: 'error', artifact_id: 'REQ-1',
  message: 'broken link', claim: 'REQ-1: broken link'
};

beforeEach(() => {
  global.fetch = jest.fn(() => { throw new Error('the model must not be called'); });
});

afterEach(() => {
  _reviewTimestamps.clear();
  _resetReviews();
  _setConfigForTesting({});
  jest.clearAllMocks();
});

describe('isReviewEnabled', () => {
  it('is true when either the model or a configured oracle is on', () => {
    expect(isReviewEnabled({ ai_review: { enabled: true } })).toBe(true);
    expect(isReviewEnabled({ ai_review: { enabled: false }, rivet_oracle: ORACLE })).toBe(true);
    expect(isReviewEnabled({ ai_review: { enabled: false }, rivet_oracle: { enabled: true } })).toBe(false);
    expect(isReviewEnabled({ ai_review: { enabled: false }, rivet_oracle: { ...ORACLE, enabled: false } })).toBe(false);
    expect(isReviewEnabled({})).toBe(false);
  });
});

describe('reviewPullRequest with ai_review off', () => {
  it('runs the oracle, calls no model, and says no model ran', async () => {
    _setConfigForTesting({ ai_review: { enabled: false }, rivet_oracle: ORACLE });
    runRivetOracle.mockResolvedValue({ ok: true, applicable: true, findings: [finding] });
    const gh = octokitFor();
    const r = await reviewPullRequest(gh, 'org', 'r', 7);
    expect(r.success).toBe(true);
    expect(r.assessment).toBe('request_changes');
    expect(runRivetOracle).toHaveBeenCalledTimes(1);
    expect(global.fetch).not.toHaveBeenCalled();
    expect(gh.posted).toHaveLength(1);
    expect(gh.posted[0]).toContain('REQ-1');
    expect(gh.posted[0]).toContain('no AI model was run');
    expect(gh.posted[0]).not.toContain('Generated by a local AI model');
  });

  it('posts nothing when the oracle finds nothing', async () => {
    _setConfigForTesting({ ai_review: { enabled: false }, rivet_oracle: ORACLE });
    runRivetOracle.mockResolvedValue({ ok: true, applicable: true, findings: [] });
    const gh = octokitFor();
    const r = await reviewPullRequest(gh, 'org', 'r', 7);
    expect(r).toMatchObject({ success: true, skipped: true, assessment: 'approve' });
    expect(gh.posted).toHaveLength(0);
    expect(global.fetch).not.toHaveBeenCalled();
  });

  it('does not refuse a remote model endpoint it will not call', async () => {
    _setConfigForTesting({
      ai_review: { enabled: false, endpoint: 'https://remote.example/v1' },
      rivet_oracle: ORACLE
    });
    runRivetOracle.mockResolvedValue({ ok: true, applicable: true, findings: [finding] });
    const r = await reviewPullRequest(octokitFor(), 'org', 'r', 7);
    expect(r.success).toBe(true);
  });

  it('does nothing when neither the model nor the oracle is enabled', async () => {
    _setConfigForTesting({ ai_review: { enabled: false }, rivet_oracle: { enabled: false } });
    const gh = octokitFor();
    const r = await reviewPullRequest(gh, 'org', 'r', 7);
    expect(r.success).toBe(false);
    expect(r.error).toMatch(/Neither AI review nor the rivet oracle/);
    expect(gh.request).not.toHaveBeenCalled();
    expect(runRivetOracle).not.toHaveBeenCalled();
  });
});
